"""
FieldProof — Violation Report Model

Stores formal violation reports generated by inspectors and confirmed by administrators.
"""

from __future__ import annotations

from datetime import datetime
from enum import Enum
from typing import TYPE_CHECKING, List, Optional

from sqlalchemy import DateTime, ForeignKey, String, Text, func
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database import Base

if TYPE_CHECKING:
    from app.models.complaint import Complaint
    from app.models.evidence import EvidenceRecord
    from app.models.inspection import Inspection
    from app.models.legal_notice import LegalNotice
    from app.models.penalty import Penalty
    from app.models.product import Product
    from app.models.user import User


class ViolationStatus(str, Enum):
    """Enforcement workflow states."""
    DRAFT = "draft"
    PENDING_ADMIN_CONFIRMATION = "pending_admin_confirmation"
    CONFIRMED = "confirmed"
    REJECTED = "rejected"
    PENALTY_ISSUED = "penalty_issued"
    NOTICE_GENERATED = "notice_generated"
    CLOSED = "closed"


class ViolationSeverity(str, Enum):
    """Severity classification."""
    MINOR = "minor"
    MODERATE = "moderate"
    MAJOR = "major"
    CRITICAL = "critical"


class ViolationReport(Base):
    """Formal violation report submitted by inspector and verified by admin."""

    __tablename__ = "violation_reports"

    id: Mapped[int] = mapped_column(primary_key=True, autoincrement=True)
    report_number: Mapped[str] = mapped_column(String(50), unique=True, index=True, nullable=False)

    # Nullable: a scan produces an EvidenceRecord and ComplianceResult but no
    # Product row, so reports are anchored on evidence instead.
    product_id: Mapped[Optional[int]] = mapped_column(
        ForeignKey("products.id", ondelete="SET NULL"), nullable=True
    )
    # The scan this report was raised from — carries the 13 rule checks, the
    # image, GPS, and the SHA-256 chain of custody.
    evidence_record_id: Mapped[Optional[int]] = mapped_column(
        ForeignKey("evidence_records.id", ondelete="SET NULL"), nullable=True, index=True
    )
    inspection_id: Mapped[Optional[int]] = mapped_column(
        ForeignKey("inspections.id", ondelete="SET NULL"), nullable=True
    )
    complaint_id: Mapped[Optional[int]] = mapped_column(
        ForeignKey("complaints.id", ondelete="SET NULL"), nullable=True
    )

    inspector_id: Mapped[int] = mapped_column(ForeignKey("users.id", ondelete="RESTRICT"), nullable=False)
    admin_id: Mapped[Optional[int]] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL"), nullable=True
    )

    status: Mapped[ViolationStatus] = mapped_column(
        String(40), default=ViolationStatus.PENDING_ADMIN_CONFIRMATION, nullable=False
    )
    severity: Mapped[ViolationSeverity] = mapped_column(
        String(20), default=ViolationSeverity.MODERATE, nullable=False
    )

    violation_summary: Mapped[str] = mapped_column(Text, nullable=False)
    violated_rules_json: Mapped[str] = mapped_column(Text, nullable=False)  # JSON array of rule codes/numbers

    inspector_notes: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    admin_notes: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    # Denormalised so the admin dashboard can render the queue without
    # joining through evidence for every row.
    shop_name: Mapped[Optional[str]] = mapped_column(String(255), nullable=True)
    shop_address: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    manufacturer_name: Mapped[Optional[str]] = mapped_column(String(255), nullable=True)
    manufacturer_address: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    product_name: Mapped[Optional[str]] = mapped_column(String(255), nullable=True)

    confirmed_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    rejected_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now(), nullable=False
    )

    # Relationships
    product: Mapped[Optional[Product]] = relationship("Product", back_populates="violation_reports")
    evidence: Mapped[Optional[EvidenceRecord]] = relationship("EvidenceRecord")
    inspection: Mapped[Optional[Inspection]] = relationship("Inspection", back_populates="violation_reports")
    complaint: Mapped[Optional[Complaint]] = relationship("Complaint", back_populates="violation_reports")
    inspector: Mapped[User] = relationship(
        "User", foreign_keys=[inspector_id], back_populates="assigned_violations"
    )
    admin: Mapped[Optional[User]] = relationship(
        "User", foreign_keys=[admin_id], back_populates="confirmed_violations"
    )

    penalties: Mapped[List[Penalty]] = relationship(
        "Penalty", back_populates="violation_report", cascade="all, delete-orphan"
    )
    legal_notices: Mapped[List[LegalNotice]] = relationship(
        "LegalNotice", back_populates="violation_report", cascade="all, delete-orphan"
    )
