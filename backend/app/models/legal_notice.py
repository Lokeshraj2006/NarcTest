"""
FieldProof — Legal Notice Model

Stores legal notices issued to manufacturers/packers/importers,
including ReportLab-generated PDF document links and response deadlines.
"""

from __future__ import annotations

from datetime import datetime
from enum import Enum
from typing import TYPE_CHECKING, Optional

from sqlalchemy import DateTime, ForeignKey, Integer, String, Text, UniqueConstraint, func
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database import Base

if TYPE_CHECKING:
    from app.models.penalty import Penalty
    from app.models.violation import ViolationReport


class NoticeStatus(str, Enum):
    """Lifecycle status of an issued legal notice."""
    GENERATED = "generated"
    DISPATCHED = "dispatched"
    DELIVERED = "delivered"
    RESPONDED = "responded"
    EXPIRED = "expired"
    CLOSED = "closed"


class LegalNotice(Base):
    """Legal notice document entity generated by ReportLab."""

    __tablename__ = "legal_notices"
    __table_args__ = (
        UniqueConstraint("violation_report_id", name="uq_legal_notices_violation_report_id"),
    )

    id: Mapped[int] = mapped_column(primary_key=True, autoincrement=True)
    notice_number: Mapped[str] = mapped_column(String(60), unique=True, index=True, nullable=False)

    violation_report_id: Mapped[int] = mapped_column(
        ForeignKey("violation_reports.id", ondelete="CASCADE"), nullable=False
    )
    penalty_id: Mapped[Optional[int]] = mapped_column(
        ForeignKey("penalties.id", ondelete="SET NULL"), nullable=True
    )

    recipient_name: Mapped[str] = mapped_column(String(255), nullable=False)
    recipient_company: Mapped[Optional[str]] = mapped_column(String(255), nullable=True)
    recipient_address: Mapped[str] = mapped_column(Text, nullable=False)
    recipient_email: Mapped[Optional[str]] = mapped_column(String(255), nullable=True)

    issuing_authority: Mapped[str] = mapped_column(
        String(255),
        default="Office of the Field Drug Testing Dashboard",
        nullable=False,
    )
    issuing_officer_name: Mapped[str] = mapped_column(String(150), nullable=False)

    statutory_clauses_cited: Mapped[str] = mapped_column(Text, nullable=False)
    notice_body: Mapped[Text] = mapped_column(Text, nullable=False)
    response_deadline_days: Mapped[int] = mapped_column(Integer, default=15, nullable=False)

    pdf_file_path: Mapped[Optional[str]] = mapped_column(String(500), nullable=True)
    pdf_sha256: Mapped[Optional[str]] = mapped_column(String(64), nullable=True)

    status: Mapped[NoticeStatus] = mapped_column(
        String(30), default=NoticeStatus.GENERATED, nullable=False
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now(), nullable=False
    )

    # Relationships
    violation_report: Mapped[ViolationReport] = relationship("ViolationReport", back_populates="legal_notices")
    penalty: Mapped[Optional[Penalty]] = relationship("Penalty", back_populates="legal_notices")
